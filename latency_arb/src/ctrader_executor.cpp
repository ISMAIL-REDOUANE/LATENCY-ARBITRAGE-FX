// connect / authenticate / resolve / subscribe (worker thread only)
// ---------------------------------------------------------------------------
bool CTraderExecutor::connect() {
    boost::system::error_code ec;
    try {
        if (stream_ && stream_->next_layer().is_open()) disconnect();

        ssl_.set_verify_mode(ssl::verify_none);   // latency — prod: verify_peer
        stream_ = std::make_unique<SslStream>(io_, ssl_);
        // SNI must be set on the raw OpenSSL handle before handshake.
        const int sni_rc = SSL_set_tlsext_host_name(stream_->native_handle(),
                                                    host_.c_str());
        if (sni_rc != 1)
            std::fprintf(stderr, "[ctrader] SNI warning for %s\n", host_.c_str());
        stream_->next_layer().set_option(asio::ip::tcp::no_delay(true), ec);
        tcp::resolver resolver(io_);
        const auto endpoints = resolver.resolve(host_, port_);
        asio::connect(stream_->next_layer(), endpoints);
        stream_->handshake(ssl::stream_base::client);
        connected_.store(true);
        std::fprintf(stderr, "[ctrader] TLS connected %s:%s\n", host_.c_str(),
                     port_.c_str());

        std::string error;
        if (!authenticate(&error)) {
            std::fprintf(stderr, "[ctrader] auth failed: %s\n", error.c_str());
            disconnect();
            return false;
        }

        const std::string sym = cfg_.ctrader_symbol.empty()
                                    ? "XAU/USD"
                                    : cfg_.ctrader_symbol;
        if (!resolve_symbol(sym, &syminfo_, &error)) {
            std::fprintf(stderr, "[ctrader] resolve symbol %s failed: %s\n",
                         sym.c_str(), error.c_str());
            disconnect();
            return false;
        }
        if (!subscribe_spot(&error)) {
            std::fprintf(stderr, "[ctrader] subscribe spots failed: %s\n",
                         error.c_str());
            disconnect();
            return false;
        }
        std::fprintf(stderr,
                     "[ctrader] ready: symbol=%s symbolId=%lld lotSize=%lld\n",
                     sym.c_str(), static_cast<long long>(syminfo_.symbol_id),
                     static_cast<long long>(syminfo_.lot_size));
        return true;
    } catch (const std::exception& e) {
        std::fprintf(stderr, "[ctrader] connect exception: %s\n", e.what());
        disconnect();
        return false;
    }
}

void CTraderExecutor::disconnect() {
    connected_.store(false);
    if (stream_) {
        try { stream_->next_layer().shutdown(tcp::socket::shutdown_both); }
        catch (...) { /* best-effort */ }
        stream_.reset();
    }
    spot_bid_.store(0.0);
    spot_ask_.store(0.0);
}

bool CTraderExecutor::authenticate(std::string* error) {
    // 1) Application auth (Client ID + Secret).
    ::ProtoOAApplicationAuthReq req;
    set_str(&req, "clientId", cfg_.ctrader_client_id);
    set_str(&req, "clientSecret", cfg_.ctrader_client_secret);
    std::string body;
    if (!req.SerializeToString(&body)) { if (error) *error = "serialize app req"; return false; }

    { std::string e;
      std::string resp = exchange(payload::APPLICATION_AUTH_REQ, body,
                                  payload::APPLICATION_AUTH_RES, &e);
      if (resp.empty()) { if (error) *error = e.empty() ? "app auth timed out" : e; return false; } }

    // 2) Account auth.
    ::ProtoOAAccountAuthReq acc;
    set_i64(&acc, "ctidTraderAccountId", account_id_);
    set_str(&acc, "accessToken", cfg_.ctrader_access_token);
    body.clear();
    if (!acc.SerializeToString(&body)) { if (error) *error = "serialize acc req"; return false; }

    std::string e;
    std::string resp = exchange(payload::ACCOUNT_AUTH_REQ, body,
                                payload::ACCOUNT_AUTH_RES, &e);
    if (resp.empty()) { if (error) *error = e.empty() ? "account auth timed out" : e; return false; }
    return true;
}

bool CTraderExecutor::resolve_symbol(const std::string& sym, SymbolInfo* out,
                                     std::string* error) {
    // List symbols, find by normalized name.
    ::ProtoOASymbolsListReq list;
    set_i64(&list, "ctidTraderAccountId", account_id_);
    std::string body;
    if (!list.SerializeToString(&body)) { *error = "serialize list req"; return false; }
    std::string resp = exchange(payload::SYMBOLS_LIST_REQ, body,
                                payload::SYMBOLS_LIST_RES, error);
    if (resp.empty()) return false;
    ::ProtoOASymbolsListRes listRes;
    if (!listRes.ParseFromString(resp)) { *error = "parse list res"; return false; }

    // Normalize broker symbol name: strip whitespace/slash, uppercase.
    auto norm = [](const std::string& s) {
        std::string o;
        for (char c : s)
            if (std::isalnum(static_cast<unsigned char>(c)))
                o.push_back(static_cast<char>(
                    std::toupper(static_cast<unsigned char>(c))));
        return o;
    };
    const std::string want = norm(sym);
    int64_t id = 0;
    for (int i = 0; i < listRes.symbol_size(); ++i) {
        const auto& ls = listRes.symbol(i);
        const std::string name = norm(str(ls, "symbolName"));
        if (name == want) { id = i64(ls, "symbolId"); break; }
    }
    if (id == 0) { if (error) *error = "symbol not found: " + sym; return false; }

    // Fetch full symbol metadata (digits, pip position, lot size).
    ::ProtoOASymbolByIdReq byid;
    set_i64(&byid, "ctidTraderAccountId", account_id_);
    add_repeated_i64(&byid, "symbolId", id);
    body.clear();
    if (!byid.SerializeToString(&body)) { *error = "serialize by-id req"; return false; }
    resp = exchange(payload::SYMBOL_BY_ID_REQ, body, payload::SYMBOL_BY_ID_RES, error);
    if (resp.empty()) return false;
    ::ProtoOASymbolByIdRes byRes;
    if (!byRes.ParseFromString(resp)) { *error = "parse by-id res"; return false; }
    if (byRes.symbol_size() == 0) { *error = "empty symbol-by-id res"; return false; }
    const auto& sp = byRes.symbol(0);
    out->symbol_id = id;
    out->digits = i32(sp, "digits");
    out->pip_position = i32(sp, "pipPosition");
    out->lot_size = i64(sp, "lotSize");   // 1 lot in 0.01-unit volume terms
    if (out->lot_size <= 0) out->lot_size = 1000000;  // 1 FX lot fallback
    out->valid = true;
    return true;
}

bool CTraderExecutor::subscribe_spot(std::string* error) {
    ::ProtoOASubscribeSpotsReq req;
    set_i64(&req, "ctidTraderAccountId", account_id_);
    add_repeated_i64(&req, "symbolId", syminfo_.symbol_id);
    std::string body;
    if (!req.SerializeToString(&body)) { *error = "serialize subscribe req"; return false; }
    std::string resp = exchange(payload::SUBSCRIBE_SPOTS_REQ, body,
                                payload::SUBSCRIBE_SPOTS_RES, error);
    if (resp.empty()) return false;

    // Wait for the first spot snapshot so we have a reference price.
    const auto deadline = std::chrono::steady_clock::now() + std::chrono::seconds(5);
    while (std::chrono::steady_clock::now() < deadline) {
        bool ok = false;
        std::string raw = read_frame(ok);
        if (!ok) { if (error) *error = "read failed during subscribe"; return false; }
        ::ProtoMessage pm;
        if (!pm.ParseFromString(raw)) continue;
        const uint32_t type = pm.payloadtype();
        if (type == payload::SPOT_EVENT) {
            ::ProtoOASpotEvent ev;
            if (ev.ParseFromString(pm.payload())) {
                if (i64(ev, "symbolId") == syminfo_.symbol_id) {
                    const uint64_t bid = u64(ev, "bid");
                    const uint64_t ask = u64(ev, "ask");
                    spot_bid_.store(static_cast<double>(bid) / kPriceScale);
                    spot_ask_.store(static_cast<double>(ask) / kPriceScale);
                    return true;
                }
            }
        }
    }
    if (error) *error = "spot snapshot not received";
    return false;
}

