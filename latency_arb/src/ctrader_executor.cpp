CTraderExecutor::CTraderExecutor(const Config& cfg) : cfg_(cfg) {
    // cTrader requires the ctidTraderAccountId as a number; parse defensively.
    char* end = nullptr;
    long long id = std::strtoll(cfg_.ctrader_account_id.c_str(), &end, 10);
    account_id_ = (end && *end == '\0') ? static_cast<int64_t>(id) : 0;
    if (!cfg_.ctrader_host.empty()) host_ = cfg_.ctrader_host;
    if (!cfg_.ctrader_port.empty()) port_ = cfg_.ctrader_port;
}
CTraderExecutor::~CTraderExecutor() { stop(); }

void CTraderExecutor::start() {
    bool expected = false;
    if (!running_.compare_exchange_strong(expected, true)) return;
    stopped_.store(false);
    thread_ = std::thread(&CTraderExecutor::worker_loop, this);
}

void CTraderExecutor::stop() {
    stopped_.store(true);
    { std::lock_guard<std::mutex> lk(mtx_); wake_ = true; }
    cv_.notify_all();
    if (thread_.joinable()) thread_.join();
    if (stream_) disconnect();
    running_.store(false);
}

void CTraderExecutor::execute(const std::string& symbol, const std::string& side,
                              double volume, double stoploss_pips,
                              double takeprofit_pips) {
    OrderJob j;
    j.symbol = symbol;
    j.side = side;
    j.volume = volume;
    j.stoploss_pips = stoploss_pips;
    j.takeprofit_pips = takeprofit_pips;
    bool dropped = false;
    {
        std::lock_guard<std::mutex> lk(mtx_);
        if (jobs_.size() >= queue_limit_) dropped = true;
        else jobs_.push_back(std::move(j));
        wake_ = true;
    }
    cv_.notify_all();
    if (dropped)
        std::fprintf(stderr, "[ctrader] queue full, order dropped (symbol=%s)\n",
                     symbol.c_str());
}

bool CTraderExecutor::connected() const {
    return connected_.load() && stream_ != nullptr;
}

void CTraderExecutor::set_result_callback(void (*cb)(const CTraderExecutionResult&, void*),
                                          void* userdata) {
    cb_ = cb;
    cb_data_ = userdata;
}

// ---------------------------------------------------------------------------
// Worker: persistent connection, serialized orders, reconnect-with-one-retry
// ---------------------------------------------------------------------------
void CTraderExecutor::worker_loop() {
    std::fprintf(stderr, "[ctrader] worker started\n");
    while (!stopped_.load()) {
        OrderJob job;
        {
            std::unique_lock<std::mutex> lk(mtx_);
            cv_.wait(lk, [this] { return wake_ || stopped_.load(); });
            if (stopped_.load()) break;
            if (jobs_.empty()) { wake_ = false; continue; }
            job = std::move(jobs_.front());
            jobs_.pop_front();
            wake_ = !jobs_.empty();
        }

        if (!connected()) {
            if (!connect()) {
                std::fprintf(stderr, "[ctrader] connect failed, worker sleeping\n");
                std::this_thread::sleep_for(std::chrono::seconds(3));
                continue;    // job dropped on connection failure (backpressure)
            }
        }

        CTraderExecutionResult r;
        for (int attempt = 1; attempt <= 2; ++attempt) {
            r = send_market_order(job);
            if (!r.ok) {
                std::fprintf(stderr, "[ctrader] order attempt %d failed: %s\n",
                             attempt, r.error.c_str());
            }
            // If the failure was a transport-level error (~1% of cases), retry
            // once after a full reconnect + re-auth.
            if (r.ok) break;
            if (attempt == 1) {
                disconnect();
                if (connect()) continue;
            }
            break;
        }

        if (cb_) cb_(r, cb_data_);
        std::fprintf(stderr,
                     "[ctrader] symbol=%s side=%s vol=%.2f -> status=%s "
                     "latency=%.2f ms\n",
                     job.symbol.c_str(), job.side.c_str(), job.volume,
                     r.status.c_str(), r.latency_ms);
    }
    std::fprintf(stderr, "[ctrader] worker stopped\n");
}

