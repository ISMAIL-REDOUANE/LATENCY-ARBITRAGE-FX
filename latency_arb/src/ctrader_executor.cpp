bool CTraderExecutor::send_frame(const std::string& payload) {
    if (!stream_ || !stream_->next_layer().is_open()) return false;
    uint8_t hdr[4];
    const uint32_t n = static_cast<uint32_t>(payload.size());
    hdr[0] = static_cast<uint8_t>((n >> 24) & 0xFF);
    hdr[1] = static_cast<uint8_t>((n >> 16) & 0xFF);
    hdr[2] = static_cast<uint8_t>((n >> 8) & 0xFF);
    hdr[3] = static_cast<uint8_t>(n & 0xFF);
    boost::system::error_code ec;
    asio::write(*stream_, asio::buffer(hdr, 4), asio::transfer_exactly(4), ec);
    if (ec) return false;
    asio::write(*stream_, asio::buffer(payload), asio::transfer_exactly(n), ec);
    return !ec;
}

std::string CTraderExecutor::read_frame(bool& ok) {
    uint8_t len[4];
    boost::system::error_code ec;
    size_t got = asio::read(*stream_, asio::buffer(len, 4), asio::transfer_exactly(4), ec);
    if (ec || got != 4) { ok = false; return {}; }
    const uint32_t n = (uint32_t(len[0]) << 24) | (uint32_t(len[1]) << 16) |
                       (uint32_t(len[2]) << 8) | uint32_t(len[3]);
    if (n == 0 || n > (1u << 20)) { ok = false; return {}; }   // sanity cap 1 MB
    std::string body(n, '\0');
    size_t rd = asio::read(*stream_, asio::buffer(&body[0], n), asio::transfer_exactly(n), ec);
    ok = (rd == n && !ec);
    return ok ? body : std::string();
}

std::string CTraderExecutor::exchange(int32_t ptype, const std::string& body,
                                      int32_t expect_type, std::string* error) {
    ::ProtoMessage out;
    out.set_payloadtype(static_cast<uint32_t>(ptype));
    out.set_payload(body);
    std::string raw;
    if (!out.SerializeToString(&raw)) { if (error) *error = "serialize ProtoMessage"; return {}; }
    if (!send_frame(raw)) { if (error) *error = "send failed (transport)"; return {}; }

    for (;;) {
        bool ok = false;
        std::string fraw = read_frame(ok);
        if (!ok) { if (error) *error = "read failed (transport)"; return {}; }
        ::ProtoMessage pm;
        if (!pm.ParseFromString(fraw)) continue;
        const int32_t got = static_cast<int32_t>(pm.payloadtype());
        if (got == expect_type) return pm.payload();
        // No match: dispatch advisory/err events, keep reading.
        std::string ls;
        if (dispatch_other(pm.payload(), got, &ls)) { if (error) *error = ls; return {}; }
    }
}

bool CTraderExecutor::dispatch_other(const std::string& raw, int32_t type,
                                     std::string* error) {
    switch (type) {
        case payload::SPOT_EVENT: {
            ::ProtoOASpotEvent ev;
            if (!ev.ParseFromString(raw)) break;
            const uint64_t bid = u64(ev, "bid");
            const uint64_t ask = u64(ev, "ask");
            spot_bid_.store(static_cast<double>(bid) / kPriceScale);
            spot_ask_.store(static_cast<double>(ask) / kPriceScale);
            break;   // not an error
        }
        case payload::ORDER_ERROR_EVENT: {
            if (error) *error = "order rejected: " + raw.substr(0, 64);
            return true;   // stop exchange with error
        }
        case payload::ERROR_RES: {
            if (error) *error = "api error: " + raw.substr(0, 64);
            return true;
        }
        case payload::CLIENT_DISCONNECT: {
            if (error) *error = "client disconnected by server";
            return true;
        }
        default:
            break;   // heartbeat / unsolicited events — ignore
    }
    return false;
}

