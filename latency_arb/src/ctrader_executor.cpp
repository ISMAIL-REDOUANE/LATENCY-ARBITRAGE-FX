CTraderExecutionResult CTraderExecutor::send_market_order(const OrderJob& job) {
    bool transport = false;
    CTraderExecutionResult r;
    try {
        r = place_order(job, &transport);
    } catch (...) {
        r.ok = false;
        r.error = "exception";
        transport = true;
    }
    return r;
}

CTraderExecutionResult CTraderExecutor::place_order(const OrderJob& job,
                                                    bool* transport_failed) {
    CTraderExecutionResult r;
    *transport_failed = false;

    // Resolve symbol id (use cached if matches, else re-resolve).
    SymbolInfo info = syminfo_;
    if (!info.valid || info.symbol_id == 0) {
        std::string e;
        if (!resolve_symbol(job.symbol, &info, &e)) { r.error = "symbol resolve: " + e; return r; }
        syminfo_ = info;
    }

    const bool buy = (job.side == "buy" || job.side == "BUY");
    const int64_t volume_proto = std::llround(job.volume * static_cast<double>(info.lot_size));
    // Convert a pips distance to Proto relative SL/TP. relativeStopLoss /
    // relativeTakeProfit are stored as 1/100000 of a price unit (kPriceScale),
    // and 1 pip == 10^(-pip_position) price units — so 1 pip in protocol units
    // is 10^(5 - pip_position). (e.g. EUR/USD pip_position=4 -> 10 protocol units.)
    const double pip_proto = std::pow(10.0, static_cast<double>(5 - info.pip_position));
    const int64_t rel_sl = static_cast<int64_t>(std::llround(job.stoploss_pips * pip_proto));
    const int64_t rel_tp = static_cast<int64_t>(std::llround(job.takeprofit_pips * pip_proto));

    ::ProtoOANewOrderReq req;
    set_i64(&req, "ctidTraderAccountId", account_id_);
    set_i64(&req, "symbolId", info.symbol_id);
    set_enum_by_name(&req, "orderType", "MARKET");
    set_enum_by_name(&req, "tradeSide", buy ? "BUY" : "SELL");
    set_i64(&req, "volume", volume_proto);
    if (rel_sl > 0) set_i64(&req, "relativeStopLoss", rel_sl);
    if (rel_tp > 0) set_i64(&req, "relativeTakeProfit", rel_tp);
    if (rel_sl > 0 || rel_tp > 0) set_enum_by_name(&req, "stopTriggerMethod", "TRADE");

    std::string clientOrderId = "LL" + std::to_string(++next_id_);
    set_str(&req, "clientOrderId", clientOrderId);

    std::string body;
    if (!req.SerializeToString(&body)) { r.error = "serialize order req"; return r; }

    const auto t0 = std::chrono::high_resolution_clock::now();
    std::string error;
    std::string resp = exchange(payload::NEW_ORDER_REQ, body,
                                payload::EXECUTION_EVENT, &error);
    if (resp.empty()) {
        *transport_failed = (error.find("transport") != std::string::npos);
        r.error = error.empty() ? "no execution event (timeout)" : error;
        return r;
    }
    const auto t1 = std::chrono::high_resolution_clock::now();
    r.latency_ms = std::chrono::duration<double, std::milli>(t1 - t0).count();

    ::ProtoOAExecutionEvent ev;
    if (!ev.ParseFromString(resp)) { r.error = "parse execution event"; return r; }
    r.status = enum_name(ev, "executionType");
    // Nest: order / position are message fields; pull ids via reflection.
    const FieldDescriptor* of = ev.GetDescriptor()->FindFieldByName("order");
    if (of) {
        const Message& ord = ev.GetReflection()->GetMessage(ev, of);
        r.order_id = i64(ord, "orderId");
    }
    const FieldDescriptor* pf = ev.GetDescriptor()->FindFieldByName("position");
    if (pf && ev.GetReflection()->HasField(ev, pf)) {
        const Message& pos = ev.GetReflection()->GetMessage(ev, pf);
        r.position_id = i64(pos, "positionId");
    }
    // Execution-event enum names are ORDER_ACCEPTED / ORDER_FILLED / ... — map
    // them to the public short status strings used by the engine.
    if (r.status == "ORDER_ACCEPTED") r.status = "ACCEPTED";
    else if (r.status == "ORDER_FILLED") r.status = "FILLED";
    else if (r.status == "ORDER_REJECTED") r.status = "REJECTED";
    r.ok = (r.status == "ACCEPTED" || r.status == "FILLED");
    if (!r.ok && r.error.empty()) r.error = "order rejected: " + r.status;
    return r;
}

